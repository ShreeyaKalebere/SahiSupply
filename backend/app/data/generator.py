"""Reproducible synthetic dataset generator (seed 42 by default).

Demand model (per outlet d, product p, day t):

    mu(d,p,t) = scale_d * base_p * weekday(t) * trend_p(t) * promo(p,t) * festival(t)
    demand    ~ NegativeBinomial(mean = mu, dispersion = 6)

Because mu is known, the forecast backtest can report a noise floor (the error
of a forecaster that knew mu exactly). All entities and outcomes are SYNTHETIC.

Contested-supply pattern (switchable): remote outlets are reachable only from
the hub warehouse W2, which is also the cheapest source for nearby urban
outlets. One-warehouse-at-a-time planning tends to fail exactly there.
"""
from __future__ import annotations

import hashlib
import json
import math
from datetime import date, timedelta

import numpy as np

from app.data import catalog

PLANNING_DATE = date(2026, 10, 26)  # Monday; fixed so the dataset is reproducible
FORECAST_HORIZON_DAYS = 14
NB_DISPERSION = 6.0
HUB_WAREHOUSE = "W2"
SYNTHETIC_LABEL = "SYNTHETIC - generated by SahiSupply for demonstration; not real company data"


def haversine_km(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    r = 6371.0
    p1, p2 = math.radians(lat1), math.radians(lat2)
    dp, dl = p2 - p1, math.radians(lon2 - lon1)
    a = math.sin(dp / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2) ** 2
    return 2 * r * math.asin(math.sqrt(a))


def _region_for(lat: float, lon: float) -> str:
    if lon >= 75.0:
        return "Vidarbha-Marathwada"
    return "Mumbai Metro" if lat >= 18.9 else "Western Maharashtra"


def _r2(x: float) -> float:
    return float(round(x, 2))


def generate_dataset(
    module: str,
    seed: int = 42,
    contested_pattern: bool = True,
    n_warehouses: int | None = None,
    n_outlets: int | None = None,
    n_products: int = 15,
    history_days: int = 180,
    planning_date: date = PLANNING_DATE,
) -> dict:
    if module not in catalog.PRODUCTS:
        raise ValueError(f"unknown module {module!r}")
    rng = np.random.default_rng([seed, catalog.MODULE_SEED_OFFSET[module]])

    raw_warehouses = catalog.WAREHOUSES.get(module, [])
    if n_warehouses is None:
        n_warehouses = len(raw_warehouses) if raw_warehouses else 4

    raw_shops = catalog.SHOPS.get(module, [])
    if n_outlets is None:
        n_outlets = len(raw_shops) if raw_shops else 8

    hub_wh = catalog.HUB_WAREHOUSES.get(module, raw_warehouses[0]["id"] if raw_warehouses else "W1")

    # ---------------- warehouses ----------------
    warehouses = []
    for i in range(n_warehouses):
        if i < len(raw_warehouses):
            rw = raw_warehouses[i]
            wid = rw["id"]
            name = rw["name"]
            city = rw["city"]
            state = rw.get("state", "")
            lat = rw["lat"]
            lon = rw["lng"]
            region = catalog.state_to_region(state)
            cold = rw.get("cold_chain", True)
            cap_num = rw.get("units", 300000)
            size = float(round(cap_num / 300000.0, 2))
            warehouses.append({
                "warehouse_id": wid, "name": name, "city": city, "state": state, "lat": lat, "lon": lon,
                "region": region, "type": rw.get("type", "Hub"), "contact": rw.get("contact", ""),
                "capacity": rw.get("capacity", ""), "status": "operational", "cold_storage": cold, "_size": size,
            })
        else:
            wid = f"WH-{module[:3].upper()}-{i + 1:02d}"
            lat, lon = float(rng.uniform(16.5, 28.5)), float(rng.uniform(72.5, 88.5))
            name, city, state = f"Regional DC {i + 1}", f"City {i + 1}", "National"
            region = catalog.state_to_region(state)
            cold, size = bool(rng.random() < 0.7), float(rng.uniform(0.7, 1.1))
            warehouses.append({
                "warehouse_id": wid, "name": name, "city": city, "state": state, "lat": lat, "lon": lon,
                "region": region, "type": "Regional Hub", "contact": "", "capacity": "",
                "status": "operational", "cold_storage": cold, "_size": size,
            })

    # ---------------- outlets ----------------
    outlets = []
    for i in range(n_outlets):
        if i < len(raw_shops):
            rs = raw_shops[i]
            did = rs["id"]
            name = rs["name"]
            city = rs["city"]
            state = rs.get("state", "")
            lat = rs["lat"]
            lon = rs["lng"]
            region = catalog.state_to_region(state)
            otype = rs.get("type", "Store")
            remote = rs.get("remote", False)
            scale = rs.get("scale", 1.0)
            cold_factor = rs.get("cold_factor", 1.0)
            storage = rs.get("storage", ("chilled",))
            outlets.append({
                "outlet_id": did, "name": name, "type": otype, "city": city, "state": state,
                "lat": lat, "lon": lon, "region": region, "remote": remote,
                "priority": rs.get("priority", "Standard"),
                "storage": ["ambient", *storage],
                "_scale": scale, "_cold_factor": cold_factor,
            })
        else:
            did = f"SH-{module[:3].upper()}-{i + 1:02d}"
            lat, lon = float(rng.uniform(16.5, 28.5)), float(rng.uniform(72.5, 88.5))
            city, state = f"Town {i + 1}", "National"
            region = catalog.state_to_region(state)
            remote = bool(rng.random() < 0.3)
            scale = float(rng.uniform(0.8, 1.4))
            outlets.append({
                "outlet_id": did, "name": f"Shop #{i + 1}", "type": "Retail Store", "city": city, "state": state,
                "lat": lat, "lon": lon, "region": region, "remote": remote, "priority": "Standard",
                "storage": ["ambient", "chilled"], "_scale": scale, "_cold_factor": 1.0,
            })

    # ---------------- products ----------------
    base_products = catalog.PRODUCTS[module]
    products = []
    for i in range(n_products):
        name, cat, storage, crit, shelf, vol, cost, price, base = base_products[i % len(base_products)]
        if i >= len(base_products):
            name = f"{name} (variant {i // len(base_products) + 1})"
            base = base * float(rng.uniform(0.6, 1.2))
        products.append({
            "product_id": f"P{i + 1:02d}", "name": name, "category": cat, "storage_class": storage,
            "criticality": crit, "shelf_life_days": shelf, "unit_volume_l": vol,
            "unit_cost": float(cost), "unit_price": float(price), "unit_margin": float(price - cost),
            "_base": base,
        })

    D, P = len(outlets), len(products)
    T = history_days + FORECAST_HORIZON_DAYS
    start = planning_date - timedelta(days=history_days)
    dates = [start + timedelta(days=t) for t in range(T)]

    # ---------------- calendar: festivals and promotions ----------------
    fest_flag = np.zeros(T, dtype=bool)
    festivals = []
    for fname, fs, fe in catalog.FESTIVALS:
        s, e = date.fromisoformat(fs), date.fromisoformat(fe)
        if e < start or s > dates[-1]:
            continue
        festivals.append({"name": fname, "start": fs, "end": fe})
        for t, d in enumerate(dates):
            if s <= d <= e:
                fest_flag[t] = True
    lo, hi = catalog.FESTIVAL_UPLIFT[module]
    fest_uplift_p = rng.uniform(lo, hi, size=P)

    promo = np.ones((P, T))
    promo_flag = np.zeros((P, T), dtype=bool)
    promotions = []
    plo, phi = catalog.PROMO_UPLIFT[module]
    for p in range(P):
        for _ in range(int(rng.integers(2, 5))):
            s = int(rng.integers(0, T - 7))
            length = int(rng.integers(4, 8))
            uplift = float(rng.uniform(plo, phi))
            promo[p, s:s + length] = np.maximum(promo[p, s:s + length], uplift)
            promo_flag[p, s:s + length] = True
            promotions.append({
                "product_id": products[p]["product_id"], "start": dates[s].isoformat(),
                "end": dates[min(s + length, T) - 1].isoformat(), "uplift": _r2(uplift),
            })

    # ---------------- expected demand mu ----------------
    wd = np.array([catalog.WEEKDAY_FACTORS[module][d.weekday()] for d in dates])
    growth = rng.uniform(-0.08, 0.18, size=P)
    trend = 1.0 + growth[:, None] * (np.arange(T)[None, :] / history_days)
    scale = np.array([o["_scale"] for o in outlets]) * rng.uniform(0.85, 1.15, size=D)
    base = np.array([p["_base"] for p in products])
    mix = rng.uniform(0.6, 1.4, size=(D, P))  # outlet-specific product mix
    if module != "pharmacy":
        # grocery/cosmetics outlets without cool storage sell little chilled product
        for di, o in enumerate(outlets):
            for pi, p in enumerate(products):
                if p["storage_class"] != "ambient" and p["storage_class"] not in o["storage"]:
                    mix[di, pi] *= 0.15
    fest = np.where(fest_flag[None, :], fest_uplift_p[:, None], 1.0)  # (P, T)
    mu = scale[:, None, None] * base[None, :, None] * mix[:, :, None] \
        * wd[None, None, :] * trend[None, :, :] * promo[None, :, :] * fest[None, :, :]

    n = NB_DISPERSION
    demand = rng.negative_binomial(n, n / (n + mu))  # (D, P, T) - includes future days

    demand_history = []
    for t in range(history_days):
        ds = dates[t].isoformat()
        for di, o in enumerate(outlets):
            for pi, p in enumerate(products):
                demand_history.append({
                    "outlet_id": o["outlet_id"], "product_id": p["product_id"], "date": ds,
                    "qty": int(demand[di, pi, t]), "promo": bool(promo_flag[pi, t]),
                    "festival": bool(fest_flag[t]), "mu": _r2(mu[di, pi, t]),
                })

    future_expected = []
    for t in range(history_days, T):
        for di, o in enumerate(outlets):
            for pi, p in enumerate(products):
                future_expected.append({
                    "outlet_id": o["outlet_id"], "product_id": p["product_id"],
                    "day_offset": t - history_days, "mu": _r2(mu[di, pi, t]),
                })

    # ---------------- capacities from expected weekly volume ----------------
    vol = np.array([p["unit_volume_l"] for p in products])
    is_cold = np.array([p["storage_class"] != "ambient" for p in products])
    week = slice(history_days, history_days + 7)
    weekly_units = mu[:, :, week].sum(axis=2)            # (D, P)
    weekly_vol = (weekly_units * vol[None, :]).sum(axis=1)  # (D,)
    weekly_cold_vol = (weekly_units * (vol * is_cold)[None, :]).sum(axis=1)

    for di, o in enumerate(outlets):
        o["receiving_capacity_l"] = _r2(weekly_vol[di] * rng.uniform(1.3, 1.7))
        cf = o.pop("_cold_factor")
        o["cold_capacity_l"] = _r2(weekly_cold_vol[di] * cf * rng.uniform(1.1, 1.4)) if cf > 0 else 0.0
        o.pop("_scale")

    # ---------------- batches ----------------
    wids = [w["warehouse_id"] for w in warehouses]
    hub = hub_wh if hub_wh in wids else wids[0]
    others = [w for w in wids if w != hub]
    batches = []
    bno = 0
    stock_vol_by_w = {w: 0.0 for w in wids}
    for pi, p in enumerate(products):
        need_week = weekly_units[:, pi].sum()
        total = need_week * rng.uniform(1.35, 1.75)
        num_others = min(2, len(others))
        holders = [hub, *sorted(rng.choice(others, size=num_others, replace=False).tolist(),
                                key=wids.index)]
        shares = rng.dirichlet(np.full(len(holders), 3.0))
        shelf = p["shelf_life_days"]
        for wid, share in zip(holders, shares, strict=False):
            k = int(rng.integers(2, 5))
            split = rng.dirichlet(np.full(k, 2.0))
            for frac in split:
                qty = int(round(total * share * frac))
                if qty <= 0:
                    continue
                # ~20% of batches are short-dated, the rest fresh (staggered expiry)
                fresh_lo = 0.6 if shelf <= 14 else 0.45   # perishables arrive from daily production
                frac = rng.uniform(0.03, 0.4) if rng.random() < 0.2 else rng.uniform(fresh_lo, 1.0)
                days_left = max(1, int(round(shelf * frac)))
                expiry = planning_date + timedelta(days=days_left)
                bno += 1
                batches.append({
                    "batch_id": f"B{bno:03d}", "product_id": p["product_id"], "warehouse_id": wid,
                    "quantity": qty, "expiry_date": expiry.isoformat(),
                    "manufacturing_date": (expiry - timedelta(days=shelf)).isoformat(),
                })
                stock_vol_by_w[wid] += qty * p["unit_volume_l"]

    avg_stock_vol = sum(stock_vol_by_w.values()) / len(wids)
    for w in warehouses:
        size = w.pop("_size")
        w["outbound_capacity_l"] = _r2(max(stock_vol_by_w[w["warehouse_id"]], 0.5 * avg_stock_vol)
                                       * size * rng.uniform(0.8, 1.0))

    # ---------------- routes ----------------
    routes = []
    for w in warehouses:
        for di, o in enumerate(outlets):
            km = haversine_km(w["lat"], w["lon"], o["lat"], o["lon"]) * 1.3
            lead = 1 + int(km // 350)
            dedicated = contested_pattern and o["remote"] and w["warehouse_id"] == hub
            is_open = not (contested_pattern and o["remote"] and w["warehouse_id"] != hub)
            cap_factor = rng.uniform(1.1, 1.4) if dedicated else rng.uniform(0.45, 0.8)
            routes.append({
                "route_id": f"{w['warehouse_id']}-{o['outlet_id']}",
                "warehouse_id": w["warehouse_id"], "outlet_id": o["outlet_id"],
                "distance_km": _r2(km), "lead_time_days": lead,
                "cost_per_litre": _r2(0.8 + 0.006 * km),
                "capacity_l": _r2(weekly_vol[di] * cap_factor),
                "open": bool(is_open),
                "distance_basis": "straight-line (haversine) x 1.3 circuity; not a road route",
            })

    # ---------------- outlet on-hand stock ----------------
    outlet_inventory = []
    for di, o in enumerate(outlets):
        for pi, p in enumerate(products):
            daily = float(mu[di, pi, history_days - 28:history_days].mean())
            qty = int(round(daily * rng.uniform(0.3, 2.5)))
            shelf = p["shelf_life_days"]
            days_left = int(rng.integers(1, shelf + 1)) if shelf <= 14 else \
                max(1, int(round(shelf * rng.uniform(0.03, 1.0))))
            outlet_inventory.append({
                "outlet_id": o["outlet_id"], "product_id": p["product_id"], "quantity": qty,
                "expiry_date": (planning_date + timedelta(days=days_left)).isoformat(),
            })

    # ---------------- open orders (orders mode) ----------------
    open_orders = []
    if module == "grocery":
        for di, o in enumerate(outlets):
            for pi, p in enumerate(products):
                realised = int(demand[di, pi, history_days:history_days + 7].sum())
                open_orders.append({
                    "order_id": f"O-{o['outlet_id']}-{p['product_id']}",
                    "outlet_id": o["outlet_id"], "product_id": p["product_id"],
                    "quantity": int(round(realised * rng.uniform(0.95, 1.15))),
                    "order_date": (planning_date - timedelta(days=1)).isoformat(),
                })

    for p in products:
        p.pop("_base")

    return {
        "meta": {
            "module": module, "seed": seed, "contested_pattern": contested_pattern,
            "planning_date": planning_date.isoformat(), "history_days": history_days,
            "history_start": start.isoformat(), "horizon_days": FORECAST_HORIZON_DAYS,
            "generator_version": "1.0.0", "label": SYNTHETIC_LABEL,
        },
        "warehouses": warehouses,
        "outlets": outlets,
        "products": products,
        "batches": batches,
        "routes": routes,
        "demand_history": demand_history,
        "open_orders": open_orders,
        "outlet_inventory": outlet_inventory,
        "calendar": {"festivals": festivals, "promotions": promotions},
        "future_expected": future_expected,
    }


def canonical_json(obj) -> bytes:
    return json.dumps(obj, sort_keys=True, separators=(",", ":"), ensure_ascii=True).encode("utf-8")


def dataset_sha256(dataset: dict) -> str:
    return hashlib.sha256(canonical_json(dataset)).hexdigest()
