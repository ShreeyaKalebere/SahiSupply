def id_sort_key(s: str) -> tuple:
    """Natural sorting key for IDs like W1, D1, WH-NES-01, SH-CIP-08."""
    nums = re.findall(r"\d+", s)
    return (s, int(nums[-1])) if nums else (s, 0)


def state_to_region(state: str) -> str:
    s = state.lower()
    if "maharashtra" in s:
        return "Western Maharashtra"
    if any(k in s for k in ("punjab", "himachal", "delhi", "haryana", "uttar pradesh")):
        return "North"
    if any(k in s for k in ("karnataka", "tamil nadu", "telangana", "andhra", "kerala")):
        return "South"
    if any(k in s for k in ("bengal", "odisha", "bihar", "assam")):
        return "East"
    if any(k in s for k in ("gujarat", "rajasthan", "goa")):
        return "West"
    if any(k in s for k in ("madhya", "chhattisgarh")):
        return "Central"
    return "National"


